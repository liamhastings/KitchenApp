import type { StoreSection } from './types';

/**
 * A static catalog of common groceries, used for two things:
 *
 *  1. Autocomplete when adding to the grocery list, so typing "chicken" offers
 *     the actual products (breast, thighs, drumsticks…) rather than making the
 *     user invent a name. Anything not in here is still addable as free text —
 *     the catalog is a convenience, never a restriction.
 *  2. A rough price estimate for the grocery list.
 *
 * PRICES ARE ESTIMATES. They are typical Canadian supermarket shelf prices,
 * before tax, for the stated `unit`. They are not live, not regional, and not
 * tied to any retailer. The UI must always present the total as an estimate —
 * see `estimateGroceryTotal` in `logic/catalog.ts`, which reports how many
 * items it could not price rather than quietly treating them as free.
 */
export interface CatalogFood {
  name: string;
  section: StoreSection;
  /** Typical CAD price for one `unit`, before tax. */
  price: number;
  /** What `price` buys, e.g. "1 lb", "dozen", "540 mL can". */
  unit: string;
}

